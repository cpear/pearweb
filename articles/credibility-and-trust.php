        So why would you pay thousands of dollars to have your website built? Two words, Credibility, and Trust. In the world of web these two items are as Jakob Nielsen puts it, &ldquo;long-term propositions that build slowly as people use a site, get good results, and don't feel let down or cheated. True trust [and credibility] comes from a company's actual behavior towards customers experienced over an extended set of encounters. It's hard to build and easy to lose: a single violation of trust can destroy years of slowly accumulated credibility&rdquo; (Jakob Nielsen).</p>
        
        <p>The ultimate goal of any business is to sell products or services to potential customers. When deciding to engage with a company it is the credibility of the business and the consumers own trust in the company which determine if he or she will do business with that company. A failure to communicate trust and credibility to a potential customer significantly decreases the chance of making a sale.</p>
        
        <p>On a website trust and credibility are achieved through presentation of quality content and visual design, through the behavior of the sites functional elements (forms, maps, shopping carts, etc.), and through the navigation system that takes the user to the content. If a company is successful in achieving credibility and trust with their website they will make money.</p>
        
        <p>Credibility and trust are built slowly over time. On the web they rely heavily on a websites behavior and appearance. When choosing between you and your competition the customer will gravitate towards the most credible and trustworthy choice. At Pear Web it is our goal to make your company that choice. <a href="../contact.php">Contact us</a> today and lets get started on your new web site.</p>

